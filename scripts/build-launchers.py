#!/usr/bin/env python3
"""Generate the self-contained Go entrypoint from the shared Python launcher."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    source = (ROOT / "trop-bootstrap.sh").read_text()
    for old, new in (
        ('readonly BACKEND="python"', 'readonly BACKEND="go"'),
        ('readonly LAUNCHER_NAME="trop-bootstrap"', 'readonly LAUNCHER_NAME="trop-bootstrap-go"'),
    ):
        if source.count(old) != 1:
            raise ValueError(f"Expected exactly one launcher constant: {old}")
        source = source.replace(old, new)
    return source.replace(
        "# SPDX-License-Identifier: Apache-2.0\n",
        "# SPDX-License-Identifier: Apache-2.0\n"
        "# Generated by scripts/build-launchers.py from trop-bootstrap.sh; do not edit.\n",
        1,
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the Go entrypoint is stale")
    args = parser.parse_args()
    destination = ROOT / "trop-bootstrap-go.sh"
    expected = generate()
    if args.check:
        if not destination.is_file() or destination.read_text() != expected:
            parser.exit(1, "Go launcher is stale; run python3 scripts/build-launchers.py\n")
    else:
        destination.write_text(expected)
        destination.chmod(0o755)
